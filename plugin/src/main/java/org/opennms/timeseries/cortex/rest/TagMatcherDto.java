package org.opennms.timeseries.cortex.rest;

/**
 * One tag matcher in a metric-explorer query. {@code type} is one of
 * EQUALS, NOT_EQUALS, EQUALS_REGEX, NOT_EQUALS_REGEX (defaults to EQUALS).
 */
public class TagMatcherDto {
    private String key;
    private String value;
    private String type;

    public TagMatcherDto() {}

    public String getKey() { return key; }
    public void setKey(String key) { this.key = key; }

    public String getValue() { return value; }
    public void setValue(String value) { this.value = value; }

    public String getType() { return type; }
    public void setType(String type) { this.type = type; }
}
